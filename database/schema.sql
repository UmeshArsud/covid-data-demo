CREATE DATABASE IF NOT EXISTS covidwatch CHARACTER SET utf8mb4;
USE covidwatch;
CREATE TABLE IF NOT EXISTS users(
  id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(30) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE, phone CHAR(10) NOT NULL,
  password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS comments(
  id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, body VARCHAR(200) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE);
CREATE TABLE IF NOT EXISTS covid_stats(
  id INT AUTO_INCREMENT PRIMARY KEY, country VARCHAR(50) UNIQUE, cases BIGINT, recovered BIGINT, deaths BIGINT);
